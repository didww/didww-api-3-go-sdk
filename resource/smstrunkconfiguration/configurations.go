// SmsToEmail forwards inbound messages as email.
// SendTo, Subject and Message are required when the trunk is created.
type SmsToEmail struct {
	SendTo  string `json:"send_to,omitempty"`
	Subject string `json:"subject,omitempty"`
	Message string `json:"message,omitempty"`
}

func (c *SmsToEmail) ConfigurationType() string { return TypeSmsToEmail }

// HTTPIn delivers inbound messages as an HTTP request. QueryParameters, Headers
// and Body may use the placeholders {SMS_TEXT}, {SMS_TEXT_BASE64_ENCODED},
// {SMS_SRC_ADDR}, {SMS_DST_ADDR} and {SMS_TIME}.
//
// URL and HTTPMethod are required when the trunk is created. BodyType and Body
// are required for post and put and refused for get. Body is a JSON string for
// json, an object (map) for the form encodings and a string for raw.
type HTTPIn struct {
	URL             string         `json:"url,omitempty"`
	HTTPMethod      string         `json:"http_method,omitempty"`
	QueryParameters map[string]any `json:"query_parameters,omitempty"`
	// Headers may carry credentials, so String and GoString redact them.
	Headers                  map[string]any `json:"headers,omitempty"`
	BodyType                 string         `json:"body_type,omitempty"`
	Body                     any            `json:"body,omitempty"`
	FollowRedirect           *bool          `json:"follow_redirect,omitempty"`
	ValidateHTTPSCertificate *bool          `json:"validate_https_certificate,omitempty"`
}

func (c *HTTPIn) ConfigurationType() string { return TypeHTTPIn }

// String implements fmt.Stringer and redacts the headers.
func (c *HTTPIn) String() string {
	headers := ""
	if len(c.Headers) > 0 {
		headers = redact.Mask(fmt.Sprint(c.Headers))
	}
	return fmt.Sprintf("HTTPIn{URL:%q HTTPMethod:%q QueryParameters:%v Headers:%q BodyType:%q Body:%v FollowRedirect:%s ValidateHTTPSCertificate:%s}",
		c.URL, c.HTTPMethod, c.QueryParameters, headers, c.BodyType, c.Body, boolString(c.FollowRedirect), boolString(c.ValidateHTTPSCertificate))
}

// GoString mirrors String for the %#v verb.
func (c *HTTPIn) GoString() string { return c.String() }

// HTTPOut accepts outbound messages submitted over HTTP. The submit URL is
// returned in the trunk's meta as "host". AuthName and AuthPassword are
// generated by DIDWW and are never sent in a request.
type HTTPOut struct {
	CallbackURL  string   `json:"callback_url,omitempty"`
	AllowedIPs   []string `json:"allowed_ips,omitempty"`
	AuthName     string   `json:"auth_name,omitempty" api:"readonly"`
	AuthPassword string   `json:"auth_password,omitempty" api:"readonly"`
}

func (c *HTTPOut) ConfigurationType() string { return TypeHTTPOut }

// MarshalJSON serializes HTTPOut for a request body, leaving out the read-only credentials.
func (c HTTPOut) MarshalJSON() ([]byte, error) { //nolint:gocritic // value receiver required for json.Marshal
	type alias HTTPOut
	return jsonapi.MarshalWritableAttrs(alias(c))
}

// String implements fmt.Stringer and redacts the generated credentials.
func (c *HTTPOut) String() string {
	return fmt.Sprintf("HTTPOut{CallbackURL:%q AllowedIPs:%v AuthName:%q AuthPassword:%q}",
		c.CallbackURL, c.AllowedIPs, redact.Mask(c.AuthName), redact.Mask(c.AuthPassword))
}

// GoString mirrors String for the %#v verb.
func (c *HTTPOut) GoString() string { return c.String() }

