// SmppSmsc makes DIDWW bind to the customer's SMSC as an SMPP client.
// Host, SystemID, Password and ServerLocation are required when the trunk is created.
// TxPort defaults to 2775 and RxPort to 2776.
type SmppSmsc struct {
	Host              string `json:"host,omitempty"`
	TxPort            *int   `json:"tx_port,omitempty"`
	RxPort            *int   `json:"rx_port,omitempty"`
	TransceiverMode   *bool  `json:"transceiver_mode,omitempty"`
	ConnectionTimeout *int   `json:"connection_timeout,omitempty"`
	UseSSL            *bool  `json:"use_ssl,omitempty"`
	SystemID          string `json:"system_id,omitempty"`
	SystemType        string `json:"system_type,omitempty"`
	Password          string `json:"password,omitempty"`
	ServerLocation    string `json:"server_location,omitempty"`
}

func (c *SmppSmsc) ConfigurationType() string { return TypeSmppSmsc }

// String implements fmt.Stringer and redacts the bind password.
func (c *SmppSmsc) String() string {
	return fmt.Sprintf("SmppSmsc{Host:%q TxPort:%s RxPort:%s TransceiverMode:%s ConnectionTimeout:%s UseSSL:%s SystemID:%q SystemType:%q Password:%q ServerLocation:%q}",
		c.Host, intString(c.TxPort), intString(c.RxPort), boolString(c.TransceiverMode), intString(c.ConnectionTimeout),
		boolString(c.UseSSL), c.SystemID, c.SystemType, redact.Mask(c.Password), c.ServerLocation)
}

// GoString mirrors String for the %#v verb.
func (c *SmppSmsc) GoString() string { return c.String() }

func boolString(b *bool) string {
	if b == nil {
		return "<nil>"
	}
	return fmt.Sprintf("%v", *b)
}

func intString(i *int) string {
	if i == nil {
		return "<nil>"
	}
	return fmt.Sprintf("%d", *i)
}
